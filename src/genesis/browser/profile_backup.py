"""A copy of a browser profile, taken before a different browser build first opens it.

A browser upgrades its profile in place the first time a different build opens it,
and the build it came from may then refuse it or damage it. So before each launch,
the launch path compares the version the profile last ran (its own record) with the
build about to open it. When they differ, it copies the profile aside to
``<profile>.pre-v<recorded>-<UTC time>``, and that copy is the way back.

Stateless: the trigger is the profile's own record, so once the new build has opened
it no further copy is made. A launch that fails before opening the profile leaves it
as it was, and a copy whose files match the profile's (path, size and mtime of
every file it copies) is still current, so the next attempt makes no other.
Every session's MCP server runs this launch path, so the check and the copy hold a
lock beside the profile: two sessions launching at once make one copy. The copy is
advisory. Nothing here raises to the launch path; a copy that cannot be made is
logged and the launch goes ahead.

Deleting copies is retention's job, not this module's: ``scripts/disk_hygiene.sh``
keeps the newest copy of each profile and removes older ones after 14 days, and an
unfinished ``*.tmp`` copy after a day.
"""

from __future__ import annotations

import configparser
import contextlib
import datetime as _dt
import fcntl
import hashlib
import json
import logging
import os
import re
import shutil
import tempfile
import time
from collections.abc import Callable, Iterator
from pathlib import Path

from genesis.browser import chromium
from genesis.util.disk_headroom import tier_after_write

logger = logging.getLogger(__name__)

# Regenerated by the browser on demand; MEASURED, they are most of a profile's size
# (354 MB of a 479 MB Camoufox profile, 160 MB of a 224 MB Chromium one).
CACHE_DIRS = ("cache2", "startupCache", "Cache", "Code Cache", "GPUCache")
# Written at the profile's root by every launch attempt, including one that fails
# before it opens the profile, so they say nothing about the profile's content.
# Below the root the same names are a site's or an extension's own data.
LOCK_NAMES = (
    "lock",
    ".parentlock",
    "parent.lock",
    "SingletonLock",
    "SingletonCookie",
    "SingletonSocket",
)
_CACHES = frozenset(CACHE_DIRS)
_ROOT_SKIP = frozenset(CACHE_DIRS + LOCK_NAMES)
_LABEL_RE = re.compile(r"[0-9A-Za-z][0-9A-Za-z._+-]{0,63}")
# A copy needs the profile's size again, plus headroom for the filesystem.
_FREE_FACTOR = 1.2
# How long a launch waits for another session's copy of the same profile. A copy of
# a ~0.5 GB profile takes seconds; a holder still busy after this is stuck (a
# stopped session, a hung filesystem), and the launch goes ahead without a copy.
_LOCK_WAIT_S = 600


# A profile written during the copy is copied again, at most this many times.
_COPY_ATTEMPTS = 3
_PROFILE_FLAGS = ("-profile", "--profile", "--user-data-dir")


class ProfileBusy(OSError):
    """The profile kept changing while it was being copied."""


class NoRoom(OSError):
    """The disk cannot take the copy (the message says why)."""


class ProfileChanged(ProfileBusy):
    """The copy does not hold the version its label names: a launch opened the
    profile with another build after the recorded version was read."""


# ── what the profile last ran, and what is about to open it ─────────────────


def firefox_profile_version(profile: Path) -> str | None:
    """``<version>_<build id>`` of the build that last opened ``profile``.

    compatibility.ini's LastVersion is ``<version>_<build id>/<platform build id>``
    (MEASURED live: ``135.0.1-beta.24_20250315105650/20250315105650``).
    """
    parser = configparser.ConfigParser(interpolation=None)
    try:
        if not parser.read(profile / "compatibility.ini", encoding="utf-8"):
            return None
        return parser.get("Compatibility", "LastVersion").split("/", 1)[0].strip() or None
    except (configparser.Error, UnicodeDecodeError, OSError):
        return None


def firefox_engine_version(binary: Path) -> str | None:
    """``<Version>_<BuildID>`` from the engine's application.ini: the string a
    profile records after this engine opens it."""
    parser = configparser.ConfigParser(interpolation=None)
    try:
        if not parser.read(Path(binary).parent / "application.ini", encoding="utf-8"):
            return None
        version = parser.get("App", "Version").strip()
        build_id = parser.get("App", "BuildID").strip()
    except (configparser.Error, UnicodeDecodeError, OSError):
        return None
    return f"{version}_{build_id}" if version and build_id else None


def chromium_profile_version(profile: Path) -> str | None:
    """The Chromium version that last opened ``profile`` (its ``Last Version`` file)."""
    try:
        return (profile / "Last Version").read_text(encoding="utf-8").strip() or None
    except (OSError, UnicodeDecodeError):
        return None


# ── is another browser using the profile? ───────────────────────────────────
# The same question as BrowserProfileManager.running_pid (genesis/browser/profile.py,
# from #2912), answered the same way: lock symlink, live pid, the profile flag's
# value, and Chromium's single-string process title. Its unknown answer differs on
# purpose: for a copy, unknown means copy (a torn copy is discarded), never skip.
# Consolidate with it once this branch carries #2912.


def _profile_args(args: list[str]) -> list[str]:
    """The values of the flags a browser is given its profile with: Firefox
    ``-profile <dir>``, Chromium ``--user-data-dir=<dir>`` or ``--user-data-dir <dir>``."""
    values = []
    for i, arg in enumerate(args):
        if arg in _PROFILE_FLAGS and i + 1 < len(args):
            values.append(args[i + 1])
        elif arg.startswith("--user-data-dir="):
            values.append(arg.split("=", 1)[1])
    return values


def _same_dir(value: str, profile: Path) -> bool:
    try:
        return Path(value).resolve() == profile.resolve()
    except (OSError, RuntimeError):
        return False


def _title_names(title: str, profile: Path) -> bool:
    """On Linux Chromium rewrites its argv into ONE space-joined process title
    (MEASURED on Playwright's chromium-1208), so the flag is a space-bounded
    substring there, not an argument of its own."""
    padded = f" {title} "
    wanted = {str(profile.absolute()), str(profile.resolve())}
    flags = ("--user-data-dir=", "--user-data-dir ", "-profile ", "--profile ")
    return any(f" {flag}{w} " in padded for w in wanted for flag in flags)


def profile_in_use(profile: Path, lock_name: str) -> bool | None:
    """Whether a live browser has ``profile`` open: True, False, or None when a live
    process holds the lock but its command line cannot be read.

    Both browsers keep a lock symlink in the profile while it is open (Firefox
    ``lock`` -> ``<ip>:+<pid>``, Chromium ``SingletonLock`` -> ``<host>-<pid>``). The
    link alone proves nothing: Camoufox leaves it after a clean close, and a crash
    leaves one too. Only a link naming a live pid whose profile flag names this
    directory counts; a sibling such as one of this module's own copies does not.
    """
    try:
        target = os.readlink(profile / lock_name)
    except OSError:
        return False
    match = re.search(r"(\d+)$", target)
    if not match or int(match[1]) <= 1:
        return False  # never probe init or the process group
    pid = int(match[1])
    try:
        os.kill(pid, 0)
    except ProcessLookupError:
        return False
    except PermissionError:
        return None  # alive, another user's
    try:
        raw = Path(f"/proc/{pid}/cmdline").read_bytes()
    except OSError:
        return None
    args = raw.decode(errors="replace").rstrip("\0").split("\0")
    if len(args) == 1 and " " in args[0]:
        return _title_names(args[0], profile)
    return any(_same_dir(value, profile) for value in _profile_args(args))


# ── the copy ─────────────────────────────────────────────────────────────────


def _skips(at_root: bool) -> frozenset[str]:
    return _ROOT_SKIP if at_root else _CACHES


def _ignore_for(profile: Path):
    root = os.path.abspath(profile)

    def ignore(directory: str, names: list[str]) -> set[str]:
        skip = _skips(os.path.abspath(directory) == root)
        return {n for n in names if n in skip}

    return ignore


def _files(profile: Path) -> Iterator[Path]:
    """Every file copy_aside copies: caches skipped everywhere, launch locks at the root."""
    root = os.path.abspath(profile)
    for dirpath, dirnames, filenames in os.walk(profile):
        skip = _skips(os.path.abspath(dirpath) == root)
        dirnames[:] = [d for d in dirnames if d not in skip]
        for name in filenames:
            if name not in skip:
                yield Path(dirpath) / name


def copy_aside(
    profile: Path,
    label: str,
    *,
    holds: Callable[[Path], bool] | None = None,
    room: Callable[[int], str | None] | None = None,
) -> Path:
    """Copy ``profile`` to ``<profile>.pre-<label>-<UTC time>`` and return it.

    The copy is built in a TemporaryDirectory beside the profile and renamed out of
    it only when complete, so a failure removes it and a killed run leaves only a
    ``*.tmp`` directory. Caches and lock files are not copied. A copy that a change
    to the profile overlapped (a write, rename or deletion) is torn, so it is
    discarded and the copy made again;
    ProfileBusy when the profile never holds still. The copy's mtime is the time it
    started, which retention ages it from. Copied files keep their size and mtime
    (copytree's copy2), which is what a later launch compares to call it current.
    ``holds`` checks the finished copy before it is published; ProfileChanged when
    it does not hold what its label names. ``room`` admits each attempt for the
    bytes of the snapshot it copies (a retry after the profile grew is judged
    again); NoRoom when it refuses.
    """
    for _ in range(_COPY_ATTEMPTS):
        started = time.time()
        stamp = _dt.datetime.fromtimestamp(started, _dt.UTC).strftime("%Y%m%dT%H%M%S")
        dest = profile.with_name(f"{profile.name}.pre-{label}-{stamp}")
        n = 1
        while dest.exists():  # a second copy within the same second
            dest = profile.with_name(f"{profile.name}.pre-{label}-{stamp}-{n}")
            n += 1
        with tempfile.TemporaryDirectory(
            dir=profile.parent, prefix=f"{dest.name}.", suffix=".tmp", ignore_cleanup_errors=True
        ) as work:
            copied = Path(work) / profile.name
            before = _snapshot(profile)
            if room is not None and (why := room(sum(e[1] for e in before.values()))):
                raise NoRoom(why)
            try:
                shutil.copytree(profile, copied, symlinks=True, ignore=_ignore_for(profile))
            except shutil.Error:
                if _snapshot(profile) != before:
                    continue  # a file vanished under the copy: torn
                raise  # unreadable, not changing: report the real error
            if _snapshot(profile) != before:
                continue  # written, renamed or deleted during the copy: torn
            if holds is not None and not holds(copied):
                raise ProfileChanged(f"the copy of {profile} does not hold {label}")
            os.utime(copied, (started, started))
            copied.rename(dest)
            return dest
    raise ProfileBusy(f"{profile} kept changing while it was being copied")


def _snapshot(profile: Path) -> dict[str, tuple[int, int, int, int]]:
    """Every file copy_aside would copy, with its inode, size, mtime and ctime. A
    write, a rename or a deletion during the copy changes it; the clock plays no
    part, so a coarse file clock or a clock stepped back cannot hide one."""
    snap: dict[str, tuple[int, int, int, int]] = {}
    for path in _files(profile):
        try:
            st = path.lstat()
        except OSError:
            continue
        snap[str(path.relative_to(profile))] = (
            st.st_ino,
            st.st_size,
            st.st_mtime_ns,
            st.st_ctime_ns,
        )
    return snap


def _digest(snapshot: dict[str, tuple[int, int, int, int]]) -> str:
    """What a copy holds: every copied file's path, size and mtime. Directory times
    and the root's launch locks are out, so a launch that never opened the profile
    leaves it unchanged; no clock is compared, so a future-dated file cannot make
    every launch look like a change. Known blind spots, none of which a browser
    produces: a same-size rewrite that restores its mtime, and a symlink to a
    directory (os.walk does not descend into it)."""
    content = sorted((rel, size, mtime) for rel, (_ino, size, mtime, _ctime) in snapshot.items())
    return hashlib.sha256(json.dumps(content).encode()).hexdigest()


def _fresh_copy(profile: Path, label: str) -> Path | None:
    """A complete copy labelled ``label`` of the profile exactly as it is now: its
    own files (no stored record) match the profile's."""
    current = _digest(_snapshot(profile))
    for copy in profile.parent.glob(f"{profile.name}.pre-{label}-*"):
        if copy.name.endswith(".tmp") or not copy.is_dir() or copy.is_symlink():
            continue
        if _digest(_snapshot(copy)) == current:
            return copy
    return None


def _lock_path(profile: Path) -> Path:
    # One lock for every profile in a directory: copies of the Camoufox and Chromium
    # profiles land on the same disk, so each admission must see the other's copy.
    return profile.parent / ".browser-profile-backup.lock"


class _LockBusy(RuntimeError):
    """Another launch held the profile's backup lock past ``_LOCK_WAIT_S``."""


@contextlib.contextmanager
def _backup_lock(profile: Path) -> Iterator[None]:
    """Held from the freshness check to the copy's publication. Another session's
    copy in progress is waited for, up to ``_LOCK_WAIT_S``."""
    deadline = time.monotonic() + _LOCK_WAIT_S
    with open(_lock_path(profile), "a") as f:
        while True:
            try:
                fcntl.flock(f, fcntl.LOCK_EX | fcntl.LOCK_NB)
                break
            except BlockingIOError:
                if time.monotonic() >= deadline:
                    raise _LockBusy(
                        f"another launch has held {_lock_path(profile)} for {_LOCK_WAIT_S} s"
                    ) from None
                time.sleep(0.2)
        yield


def backup_before_launch(
    profile: Path,
    recorded: str | None,
    engine: str | None,
    *,
    lock_name: str,
    read_version: Callable[[Path], str | None] | None = None,
) -> Path | None:
    """Copy ``profile`` aside when ``engine`` differs from the version it ``recorded``.

    Any difference counts, older as well as newer, and a version that cannot be read
    on either side counts as a difference: a missed copy of a one-way profile upgrade
    cannot be recovered, an extra one is pruned. Returns the new copy, or None when
    none was needed or one could not be made. Never raises. ``read_version`` reads
    the copy's own record before it is published: ``recorded`` was read before the
    lock, and a launch in between can have upgraded the profile.
    """
    try:
        if not profile.is_dir() or not any(profile.iterdir()):
            return None
        if recorded is not None and recorded == engine:
            return None
        label = f"v{recorded}" if recorded and _LABEL_RE.fullmatch(recorded) else "vunknown"
        with _backup_lock(profile):
            if _fresh_copy(profile, label) is not None:
                return None  # a launch that never opened the profile left it as copied
            if profile_in_use(profile, lock_name) is True:
                logger.warning("Profile %s is open in another browser; not copying it", profile)
                return None

            def room(size: int) -> str | None:
                # The disk guardian's free-space tiers (quota-aware, the watchdog's
                # thresholds): the copy must not move the disk into ORANGE or RED. A
                # disk already ORANGE still gets one unless it would reach RED, since
                # without it a one-way profile upgrade is final.
                needed = size * _FREE_FACTOR
                tiers = tier_after_write(profile.parent, needed)
                if tiers is None or tiers[1] == "red" or (tiers[1] == "orange" != tiers[0]):
                    return f"about {needed:.0f} bytes needed, disk tier now and after: {tiers}"
                return None

            def holds(copy: Path) -> bool:
                return read_version is None or read_version(copy) == recorded

            dest = copy_aside(profile, label, holds=holds, room=room)
    except (ProfileBusy, _LockBusy, NoRoom) as exc:
        logger.warning("Not copying profile %s before %s opens it: %s", profile, engine, exc)
        return None
    except Exception:  # noqa: BLE001 - advisory: a failed copy never blocks the launch
        logger.warning(
            "Could not copy profile %s before %s opens it", profile, engine, exc_info=True
        )
        return None
    logger.info(
        "Copied profile %s (last opened by %s) to %s before %s opens it",
        profile,
        recorded,
        dest,
        engine,
    )
    return dest


def backup_camoufox_profile(profile: Path, binary: Path) -> Path | None:
    """Copy the Camoufox profile before the engine at ``binary`` first opens it."""
    return backup_before_launch(
        profile,
        firefox_profile_version(profile),
        firefox_engine_version(binary),
        lock_name="lock",
        read_version=firefox_profile_version,
    )


def backup_chromium_profile(profile: Path, package: str) -> Path | None:
    """Copy the Chromium profile before the Chromium that ``package`` (playwright or
    patchright) launches first opens it."""
    package_dir = chromium.package_dir(package)
    return backup_before_launch(
        profile,
        chromium_profile_version(profile),
        chromium.browser_version(package_dir) if package_dir is not None else None,
        lock_name="SingletonLock",
        read_version=chromium_profile_version,
    )
