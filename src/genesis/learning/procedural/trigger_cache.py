"""Trigger cache for procedure advisor hook.

Generates and loads a YAML file (the human-readable source of truth) plus a
colocated ``.json`` sidecar of identical content, containing CORE and
ADVISORY-tier procedures with their tool triggers and context patterns. The
PreToolUse hook script reads this cache instead of querying the database (hook
timeout is ~2s, DB access is risky) — and prefers the JSON sidecar so it never
pays the ~40ms ``import yaml`` cost on the every-tool-call hot path.

ADVISORY procedures with tool triggers are included because they are mature
(5+ successes, 75%+ confidence) and warrant preemptive advisory. Every live
lesson (an authored row, see ``lesson_shape``) is included whatever its tier.

Each entry carries ``kind`` (``lesson`` | ``earned``), ``patterns`` (from
``trigger_spec``, else ``context_tags``), ``repeat`` and, on an unreviewed
lesson, ``label: unreviewed``. Only earned entries keep the older
``context_patterns`` key the deployed advisor matches on, so a lesson entry
matches nothing there until the advisor reads ``patterns``.

Cache is regenerated by:
- seed_procedures.py (initial population)
- promoter.py (on tier changes)
"""

from __future__ import annotations

import contextlib
import json
import logging
import os
import tempfile
from pathlib import Path

import yaml

logger = logging.getLogger(__name__)

# $GENESIS_PROCEDURE_TRIGGERS overrides the default cache location (tests /
# relocated installs); the PreToolUse advisor reads the same env var.
_CACHE_PATH = Path(
    os.environ.get("GENESIS_PROCEDURE_TRIGGERS")
    or (Path(__file__).resolve().parents[4] / "config" / "procedure_triggers.yaml")
)


def get_cache_path() -> Path:
    return _CACHE_PATH


def get_json_cache_path() -> Path:
    """Path to the colocated stdlib-loadable JSON sidecar of the trigger cache.

    Derived from the ACTIVE ``_CACHE_PATH`` at call time (not a module-level
    constant) so a caller/test that overrides only ``_CACHE_PATH`` keeps the two
    in lockstep — otherwise a redirected YAML would leave the sidecar pointing at
    the real install-local file and pollute it.
    """
    return _CACHE_PATH.with_suffix(".json")


def _atomic_write(path: Path, text: str) -> None:
    """Write ``text`` to ``path`` atomically (temp file in the same dir + rename)
    so a concurrent hook read never sees a partial file."""
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp_path = tempfile.mkstemp(dir=path.parent, suffix=".tmp")
    try:
        with os.fdopen(fd, "w") as f:
            f.write(text)
        os.rename(tmp_path, str(path))
    except Exception:
        with contextlib.suppress(OSError):
            os.unlink(tmp_path)
        raise


def _json(value: object) -> object:
    return json.loads(value) if isinstance(value, str) else value


def _trigger_spec(row: dict) -> dict | None:
    """The row's trigger_spec, or None; ValueError when it is malformed."""
    from genesis.learning.procedural.lesson_shape import validate_trigger_spec

    if row.get("trigger_spec") is None:
        return None
    return validate_trigger_spec(_json(row["trigger_spec"]))


def _entry(row: dict, tools: list, kind: str) -> dict:
    return {
        "tool": tools,
        "procedure_id": row["id"],
        "task_type": row["task_type"],
        "principle": row["principle"],
        "steps": _json(row["steps"]),
        "confidence": row["confidence"],
        "kind": kind,
    }


def _str_list(value: object) -> bool:
    return isinstance(value, list) and all(isinstance(v, str) for v in value)


def _require_reader_types(entry: dict) -> dict:
    """Raise ValueError unless every field the advisor reads has the type it uses.

    The advisor runs `tool_name in tool`, iterates the pattern lists, joins
    `steps` and formats `confidence` as a percentage, on every tool call: one
    entry of the wrong type would raise there instead of being left out here.
    With these checks every value is text, a number or a list of text, so the
    YAML and JSON writers cannot fail on a nested or binary value either.
    """
    if not entry["tool"] or not _str_list(entry["tool"]):
        raise ValueError("tool_trigger is not a list of tool names")
    for key in ("patterns", "context_patterns"):
        if key in entry and not _str_list(entry[key]):
            raise ValueError(f"{key} is not a list of strings")
    if not _str_list(entry["steps"]):
        raise ValueError("steps is not a list of strings")
    for key in ("procedure_id", "task_type", "principle"):
        if not isinstance(entry[key], str):
            raise ValueError(f"{key} is not text")
    confidence = entry["confidence"]
    if isinstance(confidence, bool) or not isinstance(confidence, int | float):
        raise ValueError("confidence is not a number")
    return entry


def _lesson_entry(row: dict) -> dict | None:
    tools = _json(row["tool_trigger"]) if row.get("tool_trigger") else None
    if not tools:
        return None
    spec = _trigger_spec(row)
    entry = _entry(row, tools, "lesson")
    entry["patterns"] = spec["patterns"] if spec else _json(row["context_tags"])
    entry["repeat"] = spec["repeat"] if spec else "session"
    if _json(row["lesson"]).get("reviewed") is not True:
        entry["label"] = "unreviewed"
    return _require_reader_types(entry)


def _earned_entry(row: dict) -> dict | None:
    tools = _json(row["tool_trigger"]) if row.get("tool_trigger") else None
    if not tools:
        return None
    # Build context patterns from context_tags for regex matching
    context_patterns = _json(row["context_tags"])
    try:
        spec = _trigger_spec(row)
    except (ValueError, RecursionError):
        logger.warning("Procedure %s has a malformed trigger_spec; using its tags", row["id"])
        spec = None
    entry = _entry(row, tools, "earned")
    entry["context_patterns"] = context_patterns
    entry["patterns"] = spec["patterns"] if spec else context_patterns
    entry["repeat"] = "every"
    return _require_reader_types(entry)


async def regenerate(db: object) -> int:
    """Regenerate trigger cache from live lessons and CORE+ADVISORY procedures.

    Uses atomic write (temp file + rename) to avoid race conditions
    with the hook reading the file.

    Returns the number of triggers written.
    """
    from genesis.db.crud import procedural
    from genesis.learning.procedural.lesson_shape import is_live_lesson

    triggers = []
    # Every live lesson, from the unbounded listing (list_by_tier stops at 100).
    for row in await procedural.list_lessons(db):  # type: ignore[arg-type]
        if not is_live_lesson(row["lesson"]):
            continue
        try:
            entry = _lesson_entry(row)
        except Exception:  # any malformed field: fail closed, this row only
            logger.warning("Lesson %s has a malformed field; left out", row["id"], exc_info=True)
            continue
        if entry:
            triggers.append(entry)

    # Include both CORE and ADVISORY procedures — ADVISORY with tool triggers
    # are mature enough (5+ successes, 75%+ confidence) to warrant hook advisories.
    rows_core = await procedural.list_by_tier(db, "CORE")  # type: ignore[arg-type]
    rows_advisory = await procedural.list_by_tier(db, "ADVISORY")  # type: ignore[arg-type]
    for row in rows_core + rows_advisory:
        # A row with a lesson record is never an earned entry: a live one is
        # listed above, a held one stays out whatever its tier.
        if row.get("lesson") is not None:
            continue
        try:
            entry = _earned_entry(row)
        except Exception:  # one bad row must not keep every other row out
            logger.warning("Procedure %s has a malformed field; left out", row["id"], exc_info=True)
            continue
        if entry:
            triggers.append(entry)

    cache_data = {
        "generated_at": __import__("datetime").datetime.now(__import__("datetime").UTC).isoformat(),
        "triggers": triggers,
    }

    # Write the YAML source of truth, then the JSON sidecar (same content). JSON
    # is written last so its mtime is >= the YAML's — the hook only trusts the
    # sidecar when it is at least as fresh as the YAML.
    _atomic_write(_CACHE_PATH, yaml.dump(cache_data, default_flow_style=False, sort_keys=False))
    _atomic_write(get_json_cache_path(), json.dumps(cache_data))

    logger.info("Regenerated procedure trigger cache: %d triggers", len(triggers))
    return len(triggers)


def load() -> list[dict]:
    """Load triggers from YAML cache. Returns empty list on any error."""
    try:
        data = yaml.safe_load(_CACHE_PATH.read_text())
        return data.get("triggers", []) if data else []
    except Exception:
        return []
